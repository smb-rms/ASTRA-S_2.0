import streamlit as st

from core import data, risk, ui, uploader


def render():
    ui.title("Mission Overview", "Centralized summary of monitoring data and current mission indicators.")
    uploader.data_manager()
    ui.missing_files_notice()
    r = risk.load()

    ui.section("Current Monitoring Snapshot", "Latest available reading for each indicator.")
    top, bottom = st.columns(3), st.columns(3)
    spec = [("sleep_hours", ["sleep"]), ("heart_rate", ["heart_rate"]), ("spo2", ["spo2"]),
            ("radiation_rate", ["radiation"]), ("cabin_temp", ["cabin_temp"]), ("glucose", ["glucose"])]
    for col, (key, status) in zip(top + bottom, spec):
        with col:
            ui.metric_card(key, status)
            st.write("")

    ui.section("Health and Environment Trends", "One chart per measurement so units are never mixed.")
    tabs = st.tabs(["Cardiovascular", "Blood glucose", "Radiation", "Sleep", "Physical activity", "Cabin"])
    with tabs[0]:
        ui.trend_grid(["heart_rate", "hrv", "spo2"], per_row=3)
    with tabs[1]:
        ui.trend("glucose", 280)
    with tabs[2]:
        ui.trend_grid(["radiation_rate", "radiation_cum"], per_row=2)
    with tabs[3]:
        ui.trend_grid(["sleep_hours", "sleep_quality"], per_row=2)
    with tabs[4]:
        ui.trend_grid(["activity", "exercise_duration", "exercise_intensity", "fatigue"], per_row=2)
    with tabs[5]:
        ui.trend_grid(["cabin_temp", "oxygen", "cabin_co2"], per_row=3)

    ui.section("Recent Monitoring Alerts", "Generated by Risk Diagnostics.")
    if r is None:
        ui.empty("No Risk Diagnostics output yet. Upload the sensor and sleep CSVs above.")
    else:
        ui.alert_cards(risk.alerts(r), r, limit=5)

    ui.section("Risk Assessment Summary", "Open Risk Assessment for full results.")
    if r is None:
        ui.empty("No Data")
        return
    lt, a = risk.latest_time(r), risk.alerts(r)
    c1, c2, c3, c4 = st.columns(4)
    with c1:
        ui.card("Active risk assessments", len(r["df"]), "", None, kind="calc")
    with c2:
        ui.card("Items requiring attention", len(a), "", None, kind="calc")
    with c3:
        ui.card("Critical alerts", risk.critical_count(r), "", None, kind="calc")
    with c4:
        ui.card("Latest assessment", lt.strftime("%Y-%m-%d %H:%M") if lt is not None else None, "", None, kind="calc")
    st.markdown(" ".join(ui.pill(f"{g}: {n}", {"Urgent": "alert", "Attention": "alert", "Monitor": "manual",
                                               "Optimal / within reference": "ok"}.get(g, "")) for g, n in risk.summary_counts(r).items()),
                unsafe_allow_html=True)
